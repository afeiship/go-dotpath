	adapter.SetFormat(dotpath.YAML)

	if adapter.GetFormat() != dotpath.YAML {
		t.Errorf("Expected YAML format, got %v", adapter.GetFormat())
	}

	// Output should now be in YAML format
	str, _ := adapter.ToString()
