	if err := yamlAdapter.LoadFromFile(yamlFile); err != nil {
		t.Fatalf("Failed to load YAML from file: %v", err)
	}

	if service := yamlAdapter.GetString("service"); service != "api" {
		t.Errorf("Expected 'api', got '%s'", service)
	}

	if port := yamlAdapter.GetInt("port"); port != 8080 {
		t.Errorf("Expected 8080, got %d", port)
	}
